#!/usr/bin/env python3
"""Audit A39b: generate `len3_instances.lean`, which applies `test1At_of_connector_mid` at each of
the order-9 roots that the Lean delta = 1 theorem certifies only through a connector of length 3
(q1 y s q2 or q1 s y q2).  Every side condition is closed by `decide` in the generated file.

usage: gen_len3_instances.py J9_d6.g6 > len3_instances.lean
"""
import importlib.util, sys
here = '/home/user/Manuscripts/research/audit/A39b-scripts/'
spec = importlib.util.spec_from_file_location('m', here + 'lean_hyp_cov.py')
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)

def good_connectors(n, J, z, r):
    k = (n - 1) // 2
    V = [v for v in range(n) if v != z]; B = {v: set(J[v]) - {z} for v in V}
    dB = {v: len(B[v]) for v in V}
    N = set(B[r]); G = {v: set(B[v]) - {r} for v in V if v != r}
    out = []
    for Q in m.paths_between_N(G, N, 7):
        EQ = {frozenset(e) for e in zip(Q, Q[1:])}
        dGp = {v: len(G[v]) - sum(1 for e in EQ if v in e) for v in G}
        if any(dGp[x] % 2 == 0 for x in N): continue
        inner = [v for v in Q[1:-1] if v in N]
        if len(inner) > 1: continue
        d = len(inner); lam = sum((dGp[v] + 1) // 2 for v in Q)
        Nt = [x for x in N if x not in Q]; h = lambda t: sum(1 for x in Nt if 2 * t <= dB[x])
        if all((h(t) + d) // 2 + (1 if t <= lam else 0) + t <= k + 1 or
               (h(t + 1) + d) // 2 + (1 if t <= lam else 0) + 2 * t <= k + 1 for t in range(3, k)):
            out.append((Q, inner, lam))
    return out

print('''import GallaiLean.DenseRootB

/-! Audit A39b (generated by `gen_len3_instances.py`): `test1At_of_connector_mid` applied at every
order-9 root (`multi-token/data/J9_d6.g6`) that the Lean `δ = 1` theorem certifies only through a
connector of length 3. These roots are among the 52 that the manuscript lists as having no connector
of length ≤ 2 (§5, §8 item 2). -/

open Gallai SimpleGraph Finset

set_option maxRecDepth 100000
set_option maxHeartbeats 4000000

def gr (n : ℕ) (L : List (ℕ × ℕ)) : SimpleGraph (Fin n) :=
  SimpleGraph.fromRel (fun a b : Fin n => (a.val, b.val) ∈ L)

instance (n : ℕ) (L : List (ℕ × ℕ)) : DecidableRel (gr n L).Adj := fun a b => by
  unfold gr; infer_instance
''')
names = []
for ln, line in enumerate(open(sys.argv[1]), 1):
    n, J = m.g6(line)
    z = [v for v in range(n) if len(J[v]) % 2 == 0][0]; Z = set(J[z])
    for r in sorted(Z):
        if len(J[r]) != n - 2: continue
        V = [v for v in range(n) if v != z]
        s = [v for v in V if v != r and v not in J[r]][0]
        if s not in Z: continue
        gc = good_connectors(n, J, z, r)
        if not gc or any(len(Q) <= 3 for Q, _, _ in gc): continue
        Q, inner, lam = gc[0]
        y = inner[0]
        E = sorted((i, j) for i in range(n) for j in J[i] if i < j)
        nm = f'L{ln}_r{r}'
        names.append(nm)
        es = ','.join(f'({a},{b})' for a, b in E)
        def sv(v): return f'(⟨{v}, by decide⟩ : {{v : Fin 9 | v ≠ {z}}})'
        # explicit: Q = [a, b, c, d]
        a, b, c, d = Q
        w = (f'Walk.cons (v := {sv(b)}) (by decide) (Walk.cons (v := {sv(c)}) (by decide) '
             f'(Walk.cons (by decide) Walk.nil))')
        print(f'''
/-- line {ln}: `{line.split()[0]}`, z = {z}, r = {r}, s = {s}, Q = {Q}, y = {y}, λ = {lam}. -/
def J_{nm} : SimpleGraph (Fin 9) := gr 9 [{es}]
instance : DecidableRel J_{nm}.Adj := by unfold J_{nm}; infer_instance
theorem hz_{nm} : J_{nm}.Adj {z} {r} := by decide
def Q_{nm} : GPath (starDel (delVert J_{nm} {z}) ⟨{r}, hz_{nm}.ne'⟩) :=
  ⟨{sv(a)}, {sv(d)}, {w}, (Walk.isPath_def _).mpr (by decide), by decide⟩
theorem t1_{nm} : Test1At J_{nm} {z} {r} :=
  test1At_of_connector_mid J_{nm} (k := 4) (by decide) (by decide) hz_{nm} (by decide) Q_{nm}
    (by decide) (by decide) {sv(y)} (by decide) (by decide) (by decide) (by decide) (by decide)
    (by decide) {lam} (by decide) (by
      intro t h1 h2
      obtain rfl : t = 3 := by omega
      left; decide)''')
print()
for nm in names: print(f'#print axioms t1_{nm}')
print(f'-- {len(names)} instances')
