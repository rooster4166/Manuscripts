HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', 'lean', 'GallaiLean', 'FiveEvenCerts.lean')


def prog(t, ind):
    if t[0] == 'done':
        return '.done'
    _, ds, r, kids = t
    sp = ' ' * ind
    if len(ds) == 1:
        return f'.offer [{ds[0]}] {r} (fun _ =>\n{sp}  {prog(kids[str(ds[0])], ind + 2)})'
    s = f'.offer [{", ".join(map(str, ds))}] {r} (fun t =>\n'
    branches = [d for d in ds if str(d) in kids]
    for d in branches:
        s += f'{sp}  if t = {d} then {prog(kids[str(d)], ind + 4)} else\n'
    s += f'{sp}  .done)'
    return s


def entry(key, c, ind=4):
    H = ', '.join(f'({a}, {b})' for a, b in c['H'])
    z0 = c['c0'].index(0)
    return f'({key}, ([{H}], {z0}, {prog(c["tree"], ind + 2)}))'


def main():
    loc = json.load(open(os.path.join(HERE, 'certs_local.json')))
    bow = json.load(open(os.path.join(HERE, 'certs_bowtie.json')))
    L = []
    L.append('-- Generated by manuscripts/bs-prescribed/scripts/gen_lean.py; do not edit by hand.')
    L.append('import GallaiLean.FiveEven\n')
    L.append(HEADER)
    L.append('/-- The 38 local certificates, keyed by the rim code. -/')
    L.append('def localTable : List (ℕ × (List (Fin 5 × Fin 5) × Fin 5 × Prog 5)) := [')
    L.append(',\n'.join('  ' + entry(c['code'], c) for c in loc))
    L.append(']\n')
    L.append('/-- The 93 bowtie certificates, keyed by `64 * contact code + rim code`. -/')
    L.append('def bowTable : List (ℕ × (List (Fin 7 × Fin 7) × Fin 7 × Prog 7)) := [')
    L.append(',\n'.join('  ' + entry(64 * c['Acode'] + c['code'], c) for c in bow))
    L.append(']\n')
    L.append(FOOTER)
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(OUT))


